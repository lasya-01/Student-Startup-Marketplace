-- 1. LISTINGS TABLE
CREATE TABLE IF NOT EXISTS public.listings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    seller_id UUID NOT NULL
        REFERENCES auth.users(id) ON DELETE CASCADE,

    title VARCHAR(80) NOT NULL,

    category TEXT NOT NULL
        CHECK (
            category IN (
                'Art & Design',
                'Fashion',
                'Tech & Digital',
                'Food & Gifts',
                'Learning',
                'Services'
            )
        ),

    price NUMERIC(10, 2) NOT NULL
        CHECK (price >= 0),

    description VARCHAR(500) NOT NULL,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. INQUIRIES TABLE
CREATE TABLE IF NOT EXISTS public.inquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    listing_id BIGINT NOT NULL
        REFERENCES public.listings(id) ON DELETE CASCADE,

    buyer_id UUID NOT NULL
        REFERENCES auth.users(id) ON DELETE CASCADE,

    message VARCHAR(1000) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. INDEXES FOR FASTER QUERIES
CREATE INDEX IF NOT EXISTS listings_seller_id_idx
    ON public.listings(seller_id);

CREATE INDEX IF NOT EXISTS listings_active_created_idx
    ON public.listings(is_active, created_at DESC);

CREATE INDEX IF NOT EXISTS inquiries_buyer_id_idx
    ON public.inquiries(buyer_id);

CREATE INDEX IF NOT EXISTS inquiries_listing_id_idx
    ON public.inquiries(listing_id);

-- 4. ENABLE ROW LEVEL SECURITY
ALTER TABLE public.listings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inquiries ENABLE ROW LEVEL SECURITY;

